import type { Storage } from '../engine/state'

export type PlatformId = 'web' | 'yandex' | 'vk' | 'telegram'

/** Адаптер витрины. Веб — нулевой: ни SDK, ни запрета внешних ссылок. */
export interface Platform {
  id: PlatformId
  /** Карточка с внешней платёжной ссылкой. На витринах платформ её нет. */
  externalPay: boolean
  init(): Promise<void>
  ready(): void
  gameplayStart(): void
  gameplayStop(): void
  /**
   * Вступить в официальное сообщество игры (VK, бонус за вступление — п. 2.6.2 правил площадки).
   * `true` — вступление подтверждено, `false` — отказ или моста нет. Нет метода — площадка такого действия не умеет.
   */
  joinGroup?(): Promise<boolean>
  /**
   * Купить «Чашку хаша для Алика» (задача lend50) за валюту площадки — единственный легальный путь
   * денег на витрине, где внешние платежи запрещены: портальная валюта Яндекса (п. 1.4 и 1.13) или
   * Telegram Stars (цифровые товары в Telegram продаются только за Stars).
   * `paid` — покупка прошла (деньги списаны), `closed` — окно закрыто или платёж не прошёл.
   * Нет метода — площадка такой покупки не умеет.
   */
  pay50?(): Promise<'paid' | 'closed'>
  /** Цена товара lend50 строкой от площадки (портальная валюта, п. 1.13.4). Нет метода — товара нет. */
  price50?(): string | null
  /**
   * Незакрытая покупка lend50, найденная и закрытая при старте (п. 1.13.1): спонсорский итог
   * ещё не выдан партии. Одноразово — второй вызов отвечает `false`.
   */
  takeSponsor?(): boolean
  /**
   * Поделиться ссылкой средствами площадки: VKWebAppShare на VK, t.me/share/url в Telegram.
   * `true` — окно площадки открыто; `false` — площадка отказала, интерфейс уходит в фолбэк.
   * Нет метода — своего механизма у площадки нет (Яндекс Игры): там остаётся браузерный Web Share или файл.
   */
  share?(text: string, url: string): Promise<boolean>
  /**
   * Хранилище прогресса витрины (облако площадки). Нет метода или `null` — прогресс в localStorage.
   * После `init()`: облачная копия уже прочитана, запись уходит в облако в фоне.
   */
  storage?(): Storage | null
}
