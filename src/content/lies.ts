/** Явные пары-противоречия (кроме групп). */
export const CONTRA: Array<[string, string]> = [
  ['sent', 'no_money'],
  ['grandpa_dead', 'grandpa_alive'],
  ['customer_owes', 'customer_paid'],
]

export const claimByKey = (k: string): Claim | undefined => CLAIMS.find((c) => c.key === k)

export function conflicts(a: string, b: string): boolean {
  if (a === b) return false
  const ca = claimByKey(a), cb = claimByKey(b)
  if (ca?.group && ca.group === cb?.group) return true
  return CONTRA.some(([x, y]) => (x === a && y === b) || (x === b && y === a))
}

export const pairKey = (a: string, b: string): string => [a, b].sort().join('|')

