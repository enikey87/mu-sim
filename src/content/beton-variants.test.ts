// Пул вариантов бетона под эталоном «с перфоратором» (#889, живая рецензия оператора №1, заметки 1, 3, 4, 7):
// конкретика, действие, персоналия. Направленный тест приёмки из задачи.
import { describe, it, expect } from 'vitest'
import { valueOf } from '../engine/rules'
import { TOPICS } from './topics'
import { ARCS } from './arcs'
import { MONEY_ASK } from './money-ask'

/** Весь пул вариантов бетона: тема, кнопки «как там» арки, денежный вопрос по месту «фундамент». */
const pool: readonly string[] = [
  ...TOPICS.beton.p.map(valueOf),
  ...ARCS.beton.follow.map(valueOf),
  ...MONEY_ASK.beton.map(valueOf),
]

describe('варианты бетона — эталон «с перфоратором» (#889)', () => {
  it('в пуле есть вариант-действие: вскрыть, достать, инструмент — не только вопросы о состоянии', () => {
    expect(pool.some((t) => /перфоратор|вскро|достан/i.test(t)), `одни вопросы о состоянии: ${pool.join(' | ')}`).toBe(true)
  })

  it('есть триггер «достать деньги из фундамента» (заметка 3)', () => {
    expect(pool.some((t) => /достанем деньги из фундамента/i.test(t)), 'триггера добычи нет').toBe(true)
  })

  it('строки заметок 1 и 7 в старом виде отсутствуют', () => {
    for (const old of ['Давайте я бетону заплачу, а он вам передаст?', 'Экскурсии к фундаменту по 500? Пусть из долга вычтут.'])
      expect(pool, `старая строка на месте: «${old}»`).not.toContain(old)
  })
})
