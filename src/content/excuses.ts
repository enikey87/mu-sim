export function make(draw: DrawFn, getTier: () => number = () => 0, rng: Rng = mathRng) {
  const g = <T = string>(k: string): T => draw(k, D[k]);
  // уровень отмазки: чаще текущий, иногда более ранний
  const escTier = () => { const t = getTier(); return t && rng.random() < [0, 0.35, 0.5, 0.6][t] ? (rng.random() < 0.65 ? t : 1 + Math.floor(rng.random() * t)) : 0; };
  const rel = (): Rel => { const [n, gen, you, id] = g('REL').split('|'); return { n, g: gen, you: you || undefined, id: id || undefined }; };
  const when = (): When => { const t = escTier(); return t ? g<When>('WHEN' + t) : g<When>('WHEN'); };
  const promise = (): Promise3 => {
    const w = when(), v: string = g('VERB');
    const text = draw('PFORM', [0, 1]) ? `${w.t} — ${v}` : `${v}, ${w.t}`;
    return { text, t: w.t, d: w.d, due: w.due, condition: w.condition };
  };
  const constr = (): string => { const t = escTier(); return t ? g('ESC' + t) : g('CONSTR'); };
  const absurd = (): string => { const t = escTier(); return t ? g('ESC' + t) : g('ABSURD'); };
  const reason = (): string => { const t = escTier(); if (t) return g('ESC' + t); const k = draw('RSRC', [0, 1, 1, 2]); return k === 2 ? g('GROT') : k ? g('CONSTR') : g('ABSURD'); };

  // каждый шаблон: () => { texts, promise, rel, constr }
  let lastEv: string | null = null;
  const ev = (): string => { const e = g('EVENT'); lastEv = e; return e; };
  const T: Array<Entry<() => ExcuseParts>> = [
    () => { const r = rel(), p = promise(), c = reason(); return { texts: [`${g('ADDR')}, у ${r.g} ${ev()}. ${c}. ${g('OATH')}, ${p.text}.`], p, r }; },
    () => { const p = promise(), c = constr(); return { texts: [`${g('ADDR')}! ${c}. ${cap(p.text)}.`], p, constr: true }; },
    () => ({ texts: [`${reason()}. ${g('OATH')}.`] }),
    () => { const r = rel(), p = promise(); return { texts: [`${g('ADDR')}, ты же знаешь, я тебя как сына люблю. Но у ${r.g} ${ev()}. ${cap(p.text)}.`], p, r }; },
    () => { const r = rel(), p = promise(); return { texts: [`${g('ADDR')}, ${g('INTRO')}`, `У ${r.g} ${ev()}.`, `${constr()}.`, `${g('OATH')}. ${cap(p.text)}.`], p, r, constr: true }; },
    () => { const p = promise(); return { texts: [`${g('ADDR')}, я за рулём, коротко: ${low(reason())}. ${cap(p.text)}.`], p }; },
    // после своих же сообщений «Кто это?» нелепо
    gate(gte('sinceAlik', 1))(() => { const r = rel(), p = promise(); return { texts: [`Кто это? А, ${low(g('ADDR'))}! У ${r.g} ${ev()}. ${cap(p.text)}.`], p, r }; }),
    () => { const r = rel(), p = promise(); return { texts: [`${g('ADDR')}, не пиши сейчас, у ${r.g} ${ev()}. ${g('OATH')}, ${p.text}.`], p, r }; },
    () => { const r = rel(), p = promise(); return { texts: [`${g('ADDR')}, деньги — это пыль. А у ${r.g} ${ev()} — вот это жизнь.`, `${cap(p.text)}.`], p, r }; },
    () => { const r = rel(), p = promise(); return { texts: [`${g('ADDR')}, ${low(constr())}.`, `${g('WOW')} А ещё у ${r.g} ${ev()}.`, `${g('OATH')}, ${p.text}.`], p, r, constr: true }; },
    () => { const p = promise(); return { texts: [`${g('ADDR')}, я уже в банке стою. ${absurd()}. ${cap(p.text)}.`], p }; },
    () => { const r = rel(), p = promise(); return { texts: [`Ара, как раз хотел тебе писать! ${reason()}. Плюс у ${r.g} ${ev()}. ${g('OATH')}, ${p.text}.`], p, r }; },
    () => { const p = promise(); return { texts: [`${g('ADDR')}, я на объекте. ${constr()}. ${constr()}. Вот так живём.`, `${cap(p.text)}.`], p, constr: true }; },
    gate(missing('act.signed'))(() => { const p = promise(); return { texts: [`${g('ADDR')}, прораб звонил: ${low(constr())}. Без акта денег нет. ${cap(p.text)}.`], p, constr: true }; }),
    () => { const p = promise(); return { texts: [`Сначала хорошая новость: ${low(constr())}. Плохая: ${low(absurd())}.`, `${g('OATH')}, ${p.text}.`], p, constr: true }; },
    () => { const r = rel(), p = promise(); return { texts: [`${g('ADDR')}, ${r.n} передаёт: «${constr()}». Я верю. ${cap(p.text)}.`], p, r, constr: true }; },
    () => { const p = promise(); return { texts: [`${g('ADDR')}, три причины. Первая: ${low(constr())}. Вторая: ${low(absurd())}. Третья — ты сам знаешь.`, `${cap(p.text)}.`], p, constr: true }; },
    () => { const r = rel(), p = promise(); return { texts: [`Смотри, ${low(g('ADDR'))}. ${cap(r.n)} — ${g('REL_ROLE')}. А там ${ev()}. Сам понимаешь.`, `${g('OATH')}, ${p.text}.`], p, r }; },
    () => { const p = promise(); return { texts: [`${g('ADDR')}, не поверишь: ${low(constr())}.`, `${g('ADDR')}, ${g('SHOCK')} ${cap(p.text)}.`], p, constr: true }; },
    () => { const p = promise(); return { texts: [`${g('ADDR')}, по деньгам всё хорошо, кроме одного: ${low(absurd())}. ${cap(p.text)}.`], p }; },
  ];

  function excuse({ preferLong = false }: { preferLong?: boolean } = {}): Excuse {
    if (draw('LEGROLL', Array.from({ length: 40 }, (_, i) => i)) === 0) {
      const l = draw('LEGENDARY', D.LEGENDARY, true);
      if (l) return { texts: [l], legendary: true };
    }
    const tpl = preferLong && draw('LONGROLL', [0, 1]) ? draw('LONGT', [4, 8, 9, 12, 14, 16, 17, 18].map((k) => T[k])) : draw('TPL', T);
    lastEv = null;
    return { ...tpl(), ev: lastEv, legendary: false };
  }

  const fill = (s: string, map: Record<string, string>): string => s.replace(/\{(\w+)\}/g, (_, k: string) => map[k] ?? '');

  return {
    D, cap, low, g, rel, when, promise, reason, constr, excuse, fill,
    short: () => g('SHORT_A') + g('SHORT_B'),
    offended: () => `${g('OFF_A')} ${(rng.random() < 0.3 && draw('OFF_ONCE', D.OFF_ONCE, true)) || g('OFF_B')}`,
    threat: () => `${g('THREAT_A')} ${g('THREAT_B')}`,
    cow: () => `${g('COW_A')} ${g('COW_B')}`,
    back: () => `${g('BACK_A')}, ${g('BACK_B')}`,
    jobYes: () => `${g('JOB_YES_A')} ${g('JOB_YES_B')}`,
    jobNo: () => `${g('JOB_NO_A')} ${g('JOB_NO_B')}`,
    promiseCheck: (t: string) => { const v = g('VERB'); return `${g('OATH')}! ${cap(t)} — ${v}. ${g('PC_TAIL')}`; },
    whyRel: (r: Rel) => { const p = promise(); return { text: `Как при чём? ${cap(r.n)} — ${g('REL_ROLE')}! ${reason()}. ${cap(p.text)}.`, p }; },
    congrats: (r: Rel) => `Спасибо, ${low(g('ADDR'))}! ${cap(r.n)} тебя тоже помнит, говорит: ${g('COMPLIMENT')}.`,
    defend: () => { const o = g('DEFEND'), c = constr(), p = promise(); return { text: `${g('ADDR')}, ${o} ${o.endsWith(':') ? low(c) : c}. ${cap(p.text)}.`, p }; },
    photo: () => `${g('PHOTO_A')} ${g('PHOTO_B')}`,
    transferQ: (): TransferReply => {
      const opening = g('TRQ_A')
      const tail = g<string | { t: string; nextTransfer: number }>('TRQ_B')
      return typeof tail === 'string' ? { text: `${opening} ${tail}` } : { text: `${opening} ${tail.t}`, nextTransfer: tail.nextTransfer }
    },
    legendQ: () => `${g('LEG_A')} ${g('LEG_B')}`,
    shortQ: (s: string) => `«${s.replace(/[.!…,].*$/, '')}» — ${g('SHORTQ')}`,
    sorry: () => `${g('SORRY_A')} ${g('SORRY_B')}`,
    ping: () => { const p = promise(); return { text: `${g('PING_A')} ${g('OATH')}, ${p.text}.`, p }; },
    prev: () => { const p = promise(); return { text: `${g('PREV_A')} ${g('PREV_B')} А вот теперь — ${p.text}.`, p }; },
  };
}


