import { type Entry, type FactOp, set, gate, is, missing, gte, lte } from '../engine/rules'
import { needs, meet, WORLD } from './world'

export type ArcMsg = string | { w: string; t: string }
export interface Episode {
  /** Сообщения серии; с needs — только уместные. */
  m: Entry<ArcMsg>[]
  /** Что меняется в мире с серией (кто появился, кто застрял) — до её сообщений. */
  remember?: FactOp[]
  /** pay — настоящие деньги игроку (долг уменьшается); offline — Алик пропадает на N дней. */
  /** days — серия занимает время (неделя работы), offline — Алик пропадает на N дней. */
  fx?: { ach?: string; debt?: number; pay?: number; offline?: number; days?: number }
  /** Трофей в досье. */
  item?: string
  /** Легенда денег (legends.ts): где деньги и что мешает; null — легенда этого сериала кончилась. */
  legend?: string | null
  /** Состояние мира на N дней (свадьба идёт, Борис болеет…); actor — чья это доска, иначе общая. */
  state?: { key: string; days: number; actor?: string }
  sys?: string
  then?: 'promise'
}
export interface Arc { title: string; minDay?: number; follow: Entry<string>[]; eps: Episode[] }
