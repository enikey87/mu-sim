export type ArcMsg = Said | { w: string; t: string; claims?: LedgerEvent[]; remember?: FactOp[] } | { t: string; claims: LedgerEvent[]; remember?: FactOp[] }
export interface Episode {
  /** Сообщения серии; с needs — только уместные. */
  m: Entry<ArcMsg>[]
  /** Что меняется в мире с серией (кто появился, кто застрял) — до её сообщений. */
  remember?: FactOp[]
  /** pay — настоящие деньги игроку (долг уменьшается); offline — Алик пропадает на N дней. */
  /** days — серия занимает время (неделя работы), offline — Алик пропадает на N дней. */
  fx?: { ach?: string; debt?: number; pay?: number; offline?: number; days?: number }
  /** Трофей в досье. */
  item?: string
  /** Легенда денег (legends.ts): где деньги и что мешает; null — легенда этого сериала кончилась. */
  legend?: string | null
  /** Состояние мира на N дней (свадьба идёт, Борис болеет…); без days — навсегда; actor — чья доска. */
  state?: { key: FactKey; days?: number; actor?: string }
  sys?: string
  then?: 'promise'
}
