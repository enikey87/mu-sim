// Состояние сериала запрещает часть упоминаний: пока Гарик в фундаменте, «в шашлычной у Гарика» — нелепо;
// пока «Нива» в бегах, «пишу с „Нивы“» — тоже. Упоминание разрешено, если оно про само состояние (unless).
const arcAt = (S: GameState, id: string) => S.arcs[id]?.i ?? 0
export const STATE_GATES: Array<{ when: (S: GameState) => boolean; re: RegExp; unless: RegExp }> = [
  { when: (S) => arcAt(S, 'garik') >= 1 && arcAt(S, 'garik') < 6, re: /Гарик/, unless: /фундамент|бетон|застыл|достал|трубочк|блог|основани/i },
  // Карине ушла к Рубику — «Карине свидетель», «жена сказала» больше не звучат
  { when: (S) => S.mem['finale.rubik'] === 'karine', re: /Карине|[Жж]ена сказала/, unless: /Рубик|ушла|бывш/i },
  // Размик слез (сериал кончился) — «с крана», «на кране» про него уже не звучит
  { when: (S) => !!S.mem['finale.razmik'], re: /Размик[^.!?]*кран|кран[^.!?]*Размик|с крана/i, unless: /слез|спустил|уволил|бывш|раньше/i },
  // после Дня выплаты «Лаваш-коин» продан
  { when: (S) => !!S.mem['payday.chain'], re: /Лаваш-коин/i, unless: /продал/i },
  { when: (S) => arcAt(S, 'niva') >= 2 && arcAt(S, 'niva') <= 5, re: /Нив[аеуыо]/, unless: /Грузи|Тбилиси|Батуми|Гюмри|границ|пропал|уехал|ищ|найд|верн|сбежал|побег|записк|бип/i },
]
