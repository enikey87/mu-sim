/** Упрёк игрока по звонку (#577): собирается оффером только при crew.paid. Имена «пострадавших»
 *  (штукатур, электрик, водитель, козёл) называет только вариант звонка — их в партии могло не
 *  звучать, и упрёк ссылался бы на то, чего не было (#703). Потому пул держит лишь то, что звонок
 *  утверждает в любом варианте: игроку не заплатили, звонил Тарон. Имя Тарона — под фактом знакомства:
 *  он сам и звонил, линтер упоминаний это и требует.
 *  Строки, утверждающие «всем заплатили», живут под fact crew.allPaid (#1057, #1068): его ставит
 *  только вариант звонка, где это прозвучало, — «плиточнику в следующий раз» о «всем» не говорит.
 *  По тому же факту гейтнута и кнопка дебютного окна P_CREW_CALL (#1170).
 *  #1057 оставил две такие строки (с вопросительным хвостом) без гейта как «инференции» — разбор
 *  раунда 84 показал, что они утверждают факт, а не спрашивают о позиции игрока; чистая инференция
 *  про себя — только «Значит, я последний в очереди». Мир вариантов 3–4 держат безымянные строки
 *  на missing(crewAllPaid): они опираются лишь на то, что эти варианты утверждают.
 *  Вокатив «я всё прочитал» держится ещё и на свежести звонка: вне окна он отвечает сообщениям, которых уже нет (#1210). */
