export type TalkKind = 'legend' | 'chorus' | 'memory' | 'arc' | 'word'
/** Пары для ответа: по легенде, персонажу, воспоминанию, реплике серии («колкость», #683) или форме клятвы. */
export const talkPairs = (kind: TalkKind, sub: string): readonly Entry<TalkPair>[] =>
  (kind === 'legend' ? LEGENDS[sub]?.talk : kind === 'chorus' ? CHORUS_TALK[sub]
    : kind === 'arc' ? ARC_TALK[sub] : kind === 'word' ? WORD_TALK : MEMORY_TALK) ?? []
export const talkId = (kind: TalkKind, sub: string, i: number) => `TALK:${kind}:${sub}:${i}`
